import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { syncAllIcons } from './sync-icons.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');
const EXTENSIONS_DIR = path.join(ROOT_DIR, 'extensions');
const RELEASES_DIR = path.join(ROOT_DIR, 'releases');

// 1. Sync all icons from root /icons folder
syncAllIcons();

// Ensure root releases directory exists
if (!fs.existsSync(RELEASES_DIR)) {
  fs.mkdirSync(RELEASES_DIR, { recursive: true });
}

console.log('\n📦 ==============================================');
console.log('   Browser Extensions Suite — Packaging All Zips  ');
console.log('==================================================\n');

const extensions = fs
  .readdirSync(EXTENSIONS_DIR, { withFileTypes: true })
  .filter((dirent) => dirent.isDirectory())
  .map((dirent) => dirent.name);

const results = [];

for (const ext of extensions) {
  const extDir = path.join(EXTENSIONS_DIR, ext);
  const pkgPath = path.join(extDir, 'package.json');

  if (!fs.existsSync(pkgPath)) {
    console.log(`⚠️  Skipping '${ext}' (no package.json found)`);
    continue;
  }

  let pkg = {};
  try {
    pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
  } catch (err) {
    console.warn(`Could not parse package.json for ${ext}:`, err);
  }

  const extName = pkg.name || ext;
  const extVersion = pkg.version || '1.0.0';

  console.log(`🔨 Building & Zipping '${extName}' (v${extVersion})...`);

  try {
    // Run npm run zip inside the extension directory
    execSync('npm run zip', {
      cwd: extDir,
      stdio: 'inherit',
    });

    const outputDir = path.join(extDir, '.output');
    if (!fs.existsSync(outputDir)) {
      console.error(`❌ Output directory not found for ${extName}`);
      continue;
    }

    // Locate the .zip generated by WXT
    const zipFiles = fs
      .readdirSync(outputDir)
      .filter((file) => file.endsWith('.zip'));

    if (zipFiles.length === 0) {
      console.error(`❌ No .zip file found in ${outputDir}`);
      continue;
    }

    // Sort by latest modified
    zipFiles.sort((a, b) => {
      return (
        fs.statSync(path.join(outputDir, b)).mtimeMs -
        fs.statSync(path.join(outputDir, a)).mtimeMs
      );
    });

    const latestZip = zipFiles[0];
    const sourceZipPath = path.join(outputDir, latestZip);
    const targetZipName = `${extName}-v${extVersion}.zip`;
    const targetZipPath = path.join(RELEASES_DIR, targetZipName);

    // Copy to root releases directory
    fs.copyFileSync(sourceZipPath, targetZipPath);
    const stats = fs.statSync(targetZipPath);
    const sizeKb = (stats.size / 1024).toFixed(2);

    results.push({
      name: extName,
      version: extVersion,
      filename: targetZipName,
      size: `${sizeKb} KB`,
      path: `releases/${targetZipName}`,
    });

    console.log(`✅ Saved: releases/${targetZipName} (${sizeKb} KB)\n`);
  } catch (err) {
    console.error(`❌ Error packaging ${extName}:`, err.message);
  }
}

console.log('🎉 ==============================================');
console.log('   Summary of Packaged Extensions:               ');
console.log('==================================================');
console.table(results);
console.log(`\n📂 All packages are ready in: ${RELEASES_DIR}\n`);
