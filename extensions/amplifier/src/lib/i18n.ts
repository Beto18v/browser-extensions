/**
 * Traduce una clave para el idioma especificado con fallback a 'en'
 */
export function t(locale: Locale, key: string, params?: Record<string, string | number>): string {
  const dict = TRANSLATIONS[locale] || TRANSLATIONS.en;
  let text = dict[key] || TRANSLATIONS.en[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{\\{${k}\\}\\}`, 'g'), String(v));
    }
  }
  return text;
}

/**
 * Detecta el idioma del navegador mapeándolo a los 6 soportados
 */
export function detectBrowserLocale(): Locale {
  try {
    const raw = (navigator?.language || 'en').toLowerCase().replace('_', '-');
    if (raw.startsWith('es')) return 'es';
    if (raw.startsWith('pt')) return 'pt_BR';
    if (raw.startsWith('fr')) return 'fr';
    if (raw.startsWith('de')) return 'de';
    if (raw.startsWith('ja')) return 'ja';
    return 'en';
  } catch {
    return 'en';
  }
}
